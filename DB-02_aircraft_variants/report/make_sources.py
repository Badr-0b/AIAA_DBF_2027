"""Write report/data/sources.tex from W/sources/*.toml (+ the repo's standing primary documents).
Run: PYTHONDONTWRITEBYTECODE=1 python report/make_sources.py"""
import sys
import tomllib
from pathlib import Path

sys.dont_write_bytecode = True
W = Path(__file__).resolve().parents[1]
OUT = W / "report" / "data" / "sources.tex"

STANDING = [
    ("AIAA", 2026, "2026-27 Design/Build/Fly Competition Rules (draft of 2 September 2026)",
     "rules/2027_DBF_Rules_Draft.pdf; SHA-256 d94773fb...ae1", "All rule quotes, by line of the layout text"),
    ("AIAA", 2026, "DBF competition summaries and top-3 design reports, 2021-26",
     "aiaa.org; registry analysis/data/sources.toml (1,008 verified values)", "Field data, mass, drag, lap times"),
    ("Team (DB-01)", 2026, "DB-01 Sizing and configuration decision brief, revision A, 14 October 2026",
     "decisions/DB-01_sizing_and_configuration.pdf", "Baseline and control design"),
    ("Team (analysis)", 2026, "Analysis Scripts 1-6 and 3b; SOURCES.md registry (113 sources)",
     "analysis/; SOURCES.md", "Scoring, sizing, propulsion and Monte Carlo models"),
]


def _breakable(tok, n=14):
    return "\x00".join(tok[i:i + n] for i in range(0, len(tok), n)) if len(tok) > n else tok


def esc(s):
    s = " ".join(_breakable(t) for t in str(s).split(" "))
    s = s.replace("/", "/\x00").replace("-", "-\x00")
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"),
                 ("_", "\\_"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\^{}")):
        s = s.replace(a, b)
    return s.replace("\x00", "\\allowbreak{}")


def main():
    rows = []
    for a, y, t, u, used in STANDING:
        rows.append(("REF", a, y, t, u, "", used, "PRIMARY"))
    for f in sorted(W.glob("sources/*.toml")):
        try:
            d = tomllib.loads(f.read_text(encoding="utf-8"))
        except Exception as e:  # noqa: BLE001
            print("skip", f, e)
            continue
        for s in d.get("source", []):
            rows.append((s.get("id", f.stem), s.get("author", ""), s.get("year", ""), s.get("title", ""),
                         s.get("url", ""), s.get("date_read", ""), s.get("used", ""), s.get("nature", "")))
    out = ["% generated by report/make_sources.py; do not edit",
           "\\begin{dbflongtable}{colspec={Q[l,wd=0.95in] X[3,l] Q[l,wd=0.7in]}, width=\\textwidth}",
           "Source & Reference and use & Nature \\\\"]
    for (i, a, y, t, u, dr, used, nat) in rows:
        ref = f"{esc(str(a))} ({esc(str(y))}). \\emph{{{esc(str(t))}}}. {{\\small\\color{{dbfSteel}}{esc(str(u))}" + \
              (f"; read {esc(str(dr))}" if dr else "") + "}" + (f"\\newline{{\\small {esc(str(used))}}}" if used else "")
        out.append(f"{{\\small\\ttfamily {esc(str(i))}}} & {ref} & {{\\small {esc(str(nat))}}} \\\\")
    out.append("\\end{dbflongtable}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} sources -> {OUT}")


if __name__ == "__main__":
    main()
