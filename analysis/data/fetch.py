"""Download every source in sources.toml and cache its text (TOOLING).

    python analysis/data/fetch.py            fetch what is missing
    python analysis/data/fetch.py --force    re-download everything

- Files go to analysis/data/raw/<id>.pdf (gitignored); names come from the
  registry, never from the server, and only PDFs are accepted (magic bytes).
- sources.lock records the SHA-256, size, page count and fetch date of each
  file, so anyone can re-fetch and confirm they read the same document.
- raw/<id>.txt (reading order), .layout.txt (columns kept) and .raw.txt
  (content-stream order) are the pdftotext caches that verify.py checks every
  quoted value against.
"""
import datetime as dt
import hashlib
import shutil
import subprocess
import sys
import tomllib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw"
REPO = HERE.parents[1]
LOCK = HERE / "sources.lock"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"


def sources():
    with (HERE / "sources.toml").open("rb") as f:
        return tomllib.load(f)["source"]


def download(url, dest):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    tmp = dest.with_suffix(".part")
    with urllib.request.urlopen(req, timeout=120) as r, tmp.open("wb") as f:
        shutil.copyfileobj(r, f, length=1 << 20)
    with tmp.open("rb") as f:
        if f.read(5) != b"%PDF-":
            tmp.unlink()
            raise ValueError(f"{url} is not a PDF")
    tmp.replace(dest)


def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def pages(path):
    out = subprocess.run(["pdfinfo", str(path)], capture_output=True, text=True).stdout
    return next((int(l.split()[-1]) for l in out.splitlines() if l.startswith("Pages:")), 0)


def main(force=False):
    RAW.mkdir(exist_ok=True)
    rows = ["# GENERATED by fetch.py: what was read, so it can be re-checked.",
            "# id, sha256, bytes, pages, fetched"]
    for s in sources():
        if s["url"].startswith("repo:"):
            pdf = REPO / s["url"][5:]
        else:
            pdf = RAW / f"{s['id']}.pdf"
            if force or not pdf.exists():
                print(f"fetch  {s['id']}  <- {s['url']}", flush=True)
                download(s["url"], pdf)
        for mode, suffix in ((["-enc", "UTF-8"], ".txt"), (["-enc", "UTF-8", "-layout"], ".layout.txt"),
                             (["-enc", "UTF-8", "-raw"], ".raw.txt")):
            txt = RAW / f"{s['id']}{suffix}"
            if force or not txt.exists() or txt.stat().st_mtime < pdf.stat().st_mtime:
                subprocess.run(["pdftotext", *mode, str(pdf), str(txt)], check=True)
        fetched = dt.date.fromtimestamp(pdf.stat().st_mtime).isoformat()
        rows.append(f"{s['id']}, {sha256(pdf)}, {pdf.stat().st_size}, {pages(pdf)}, {fetched}")
        print(f"ok     {s['id']}  {pages(pdf)} pages", flush=True)
    LOCK.write_text("\n".join(rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(force="--force" in sys.argv)
