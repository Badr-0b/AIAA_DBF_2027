"""Download every aerodynamics source in aero/sources.toml and cache its text (TOOLING).

    python analysis/data/aero/fetch_aero.py            fetch what is missing
    python analysis/data/aero/fetch_aero.py --force    re-download everything

Same rules as prop/fetch_prop.py, whose download and check functions it reuses:
files go to analysis/data/raw/aero/<id>.<ext> (gitignored), named from the
registry; content is checked by kind; sources.lock records SHA-256, size and
date; raw/aero/<id>.txt holds the text verify_aero.py checks quotes against.
"""
import datetime as dt
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "prop"))
from fetch_prop import EXT, curl, download, sha256, visible_text  # noqa: E402

RAW = HERE.parent / "raw" / "aero"
LOCK = HERE / "sources.lock"
EXT = {**EXT, "dat": ".dat"}


def download_dat(src, dest):
    """A coordinate file: a name line, then x y pairs with x in [0, 1] (Selig), or a
    point-count line first (Lednicer; coords.py reads both)."""
    part = dest.with_suffix(dest.suffix + ".part")
    curl(src["url"], part)
    lines = part.read_text(encoding="latin-1").splitlines()
    pts = [l.split() for l in lines[1:] if l.strip()]
    if pts and len(pts[0]) == 2 and float(pts[0][0]) > 1.5:      # Lednicer count line
        pts = pts[1:]
    ok = len(pts) > 20 and all(len(p) == 2 and -0.01 <= float(p[0]) <= 1.01 for p in pts)
    if not ok:
        part.unlink()
        raise ValueError(f"{src['id']}: {src['url']} is not a coordinate file")
    part.replace(dest)


def sources():
    with (HERE / "sources.toml").open("rb") as f:
        return tomllib.load(f)["source"]


def write_text(src, path):
    txt = RAW / f"{src['id']}.txt"
    if src["kind"] == "html":
        txt.write_text(visible_text(path.read_text(encoding="utf-8", errors="replace")), encoding="utf-8")
    elif src["kind"] == "pdf":
        subprocess.run(["pdftotext", "-enc", "UTF-8", "-layout", str(path), str(txt)], check=True)


def main(force=False):
    RAW.mkdir(parents=True, exist_ok=True)
    rows = ["# GENERATED by fetch_aero.py: what was read, so it can be re-checked.",
            "# id, sha256, bytes, fetched (local date), url"]
    bad = 0
    for s in sources():
        path = RAW / f"{s['id']}{EXT[s['kind']]}"
        try:
            if force or not path.exists():
                print(f"fetch  {s['id']}  <- {s['url']}", flush=True)
                (download_dat if s["kind"] == "dat" else download)(s, path)
            write_text(s, path)
        except (subprocess.CalledProcessError, ValueError) as e:
            print(f"FAIL   {s['id']}: {e}", flush=True)
            bad += 1
            continue
        fetched = dt.date.fromtimestamp(path.stat().st_mtime).isoformat()
        rows.append(f"{s['id']}, {sha256(path)}, {path.stat().st_size}, {fetched}, {s['url']}")
        print(f"ok     {s['id']}  {path.stat().st_size} bytes", flush=True)
    LOCK.write_text("\n".join(rows) + "\n", encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(force="--force" in sys.argv))
