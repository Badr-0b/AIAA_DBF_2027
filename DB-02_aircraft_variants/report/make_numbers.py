"""Write report/data/numbers.tex from every W/out/*/results.json (and W/out/finalists/*.json).

Each result item S<n>-R<nn> becomes  \\defval{S3-R04}{<value>}{<unit>}{<grade>}{<range>}.
In the text:  \\val{S3-R04}  prints the value (+ unit with \\valu),  \\grade{S3-R04}  the grade tag,
\\rng{S3-R04} the range.  An ID with no value prints as a visible \\dbftbd tag and is counted by the build.

Run:  PYTHONDONTWRITEBYTECODE=1 python report/make_numbers.py
"""
import json
import math
import re
import sys
from pathlib import Path

W = Path(__file__).resolve().parents[1]
OUT = W / "report" / "data" / "numbers.tex"

UNIT_TEX = {"m2": "m²", "m^2": "m²", "kg/m3": "kg/m³", "kg/m^3": "kg/m³", "N/m2": "N/m²", "N/m^2": "N/m²",
            "-": "", "": ""}
GRADES = {"verified": "\\gV", "reseller": "\\gR", "estimate": "\\gE", "computed": "\\gC"}


def fmt(v):
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int,)):
        return f"{v:,}".replace(",", "\\,")
    if isinstance(v, float):
        if math.isnan(v):
            return None
        a = abs(v)
        if a == 0:
            return "0"
        if a >= 1000:
            return f"{v:,.0f}".replace(",", "\\,")
        if a >= 100:
            return f"{v:.0f}"
        if a >= 10:
            return f"{v:.1f}"
        if a >= 1:
            return f"{v:.2f}"
        return f"{v:.3f}".rstrip("0").rstrip(".") if a < 0.01 else f"{v:.3g}"
    if isinstance(v, str):
        return tex_escape(v)
    return None


def tex_escape(s):
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"),
                 ("_", "\\_"), ("{", "\\{"), ("}", "\\}")):
        s = s.replace(a, b)
    return s


PROB_ID = re.compile(r"-(PTOP|P1ST|REG|MAXREG|PM2D|PM3D|PM2|PM3|FEAS|CD0UPP)(-|$)|^F-AB-")


def fmt_id(k, v):
    """Probabilities and regrets print with three decimals (0.300, not 0.3) so table columns line up."""
    if PROB_ID.search(k) and isinstance(v, float) and not math.isnan(v):
        return f"{v:.3f}".replace("-", "$-$")
    return fmt(v)


def rng(r, k=""):
    if isinstance(r, (list, tuple)) and len(r) == 2 and all(isinstance(x, (int, float)) for x in r):
        a, b = (fmt_id(k, float(x)) for x in r)
        return f"{a} to {b}" if min(r) < 0 else f"{a}--{b}"
    return ""


def main():
    files = sorted(W.glob("out/*/results.json")) + sorted(W.glob("out/finalists/*.json"))
    lines = ["% generated by report/make_numbers.py; do not edit", ""]
    n, bad = 0, []
    for f in files:
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except Exception as e:  # noqa: BLE001
            bad.append(f"{f}: {e}")
            continue
        items = d.get("items", {})
        lines.append(f"% {f.relative_to(W).as_posix()} ({len(items)} items)")
        for k, it in items.items():
            if not isinstance(it, dict):
                continue
            v = fmt_id(k, it.get("value"))
            if v is None:
                continue
            u = it.get("unit", "")
            u = UNIT_TEX.get(u, tex_escape(str(u)))
            g = GRADES.get(str(it.get("grade", "")).lower(), "")
            lines.append(f"\\defval{{{k}}}{{{v}}}{{{u}}}{{{g}}}{{{rng(it.get('range'), k)}}}")
            n += 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{n} values from {len(files)} files -> {OUT}")
    for b in bad:
        print("  skipped", b, file=sys.stderr)


if __name__ == "__main__":
    main()
