"""Download every propulsion source in prop/sources.toml and cache its text (TOOLING).

    python analysis/data/prop/fetch_prop.py            fetch what is missing
    python analysis/data/prop/fetch_prop.py --force    re-download everything

- Files go to analysis/data/raw/prop/<id>.<ext> (gitignored); names come from the
  registry, never from the server. Content is checked by kind (zip/pdf magic
  bytes; html must be a page and not a bot-block page).
- curl does the download: several of these servers refuse Python's urllib, and
  APC serves its files only to a session that has opened the referring page.
- sources.lock records the SHA-256, size and fetch date of each file, so anyone
  can re-fetch and confirm they read the same document.
- raw/prop/<id>.txt is the text verify_prop.py checks quotes against: the page's
  visible text (one block per line) for html, pdftotext -layout for pdf.
"""
import datetime as dt
import hashlib
import html
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE.parent / "raw" / "prop"
LOCK = HERE / "sources.lock"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"
EXT = {"zip": ".zip", "xlsx": ".xlsx", "pdf": ".pdf", "html": ".html", "json": ".json"}
BLOCKED = ("Attention Required! | Cloudflare", "you have been blocked", "403 - Forbidden")


def sources():
    with (HERE / "sources.toml").open("rb") as f:
        return tomllib.load(f)["source"]


def curl(url, dest, referer=None, jar=None):
    args = ["curl", "-sS", "-L", "--fail", "--max-time", "600", "-A", UA,
            "-H", "Accept-Language: en-US,en;q=0.9", "-o", str(dest)]
    if jar:
        args += ["-c", str(jar), "-b", str(jar)]
    if referer:
        args += ["-H", f"Referer: {referer}"]
    subprocess.run(args + [url], check=True)


def download(src, dest):
    with tempfile.TemporaryDirectory() as tmp:
        jar = Path(tmp) / "cookies.txt"
        if src.get("referer"):                        # open the referring page first (session cookie)
            curl(src["referer"], Path(tmp) / "referer.html", jar=jar)
        part = dest.with_suffix(dest.suffix + ".part")
        curl(src["url"], part, referer=src.get("referer"), jar=jar)
    head = part.read_bytes()[:4096]
    kind = src["kind"]
    ok = {"zip": head.startswith(b"PK\x03\x04"), "xlsx": head.startswith(b"PK\x03\x04"),
          "pdf": head.startswith(b"%PDF-"),
          "json": head.lstrip()[:1] in (b"{", b"["),
          "html": b"<html" in head.lower() or b"<!doctype html" in head.lower()}[kind]
    if not ok:
        part.unlink()
        raise ValueError(f"{src['id']}: {src['url']} is not a {kind}")
    if kind == "html":
        text = part.read_text(encoding="utf-8", errors="replace")
        if any(b in text for b in BLOCKED):
            part.unlink()
            raise ValueError(f"{src['id']}: the server returned a block page")
    part.replace(dest)


def visible_text(raw_html):
    """The page's visible text, one block (cell, row, paragraph) per line."""
    t = re.sub(r"<script.*?</script>|<style.*?</style>|<noscript.*?</noscript>", " ", raw_html, flags=re.S | re.I)
    t = re.sub(r"<(br|/p|/tr|/li|/h\d|/div|/td|/th)[^>]*>", "\n", t, flags=re.I)
    t = html.unescape(re.sub(r"<[^>]+>", " ", t))
    return "\n".join(l for l in (" ".join(x.split()) for x in t.splitlines()) if l) + "\n"


def write_text(src, path):
    txt = RAW / f"{src['id']}.txt"
    if src["kind"] == "html":
        txt.write_text(visible_text(path.read_text(encoding="utf-8", errors="replace")), encoding="utf-8")
    elif src["kind"] == "pdf":
        subprocess.run(["pdftotext", "-enc", "UTF-8", "-layout", str(path), str(txt)], check=True)


def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main(force=False):
    RAW.mkdir(parents=True, exist_ok=True)
    rows = ["# GENERATED by fetch_prop.py: what was read, so it can be re-checked.",
            "# id, sha256, bytes, fetched (local date), url"]
    bad = 0
    for s in sources():
        path = RAW / f"{s['id']}{EXT[s['kind']]}"
        try:
            if force or not path.exists():
                print(f"fetch  {s['id']}  <- {s['url']}", flush=True)
                download(s, path)
            write_text(s, path)
        except (subprocess.CalledProcessError, ValueError) as e:
            print(f"FAIL   {s['id']}: {e}", flush=True)
            bad += 1
            continue
        fetched = dt.date.fromtimestamp(path.stat().st_mtime).isoformat()
        rows.append(f"{s['id']}, {sha256(path)}, {path.stat().st_size}, {fetched}, {s['url']}")
        print(f"ok     {s['id']}  {path.stat().st_size} bytes", flush=True)
    LOCK.write_text("\n".join(rows) + "\n", encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(force="--force" in sys.argv))
