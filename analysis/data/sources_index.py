"""Write SOURCES.md: every source behind any number in the repo, with its link (TOOLING).

    python analysis/data/sources_index.py

Merges, without retyping anything:
  analysis/data/sources.toml + sources.lock          AIAA documents (hashes, pages, fetch dates)
  analysis/data/prop/sources.toml + sources.lock     propulsion sources (hashes, fetch dates)
  analysis/data/other_sources.toml                   site, weather, D&R parts, methods, consulted
  procurement/pr01_items.csv                         price links (PR-01)
  brainstorm.md                                      links behind the brainstorm notes
and counts how many verified values each source supplies (dbf_aircraft.csv,
dbf_results.csv, prop/components.csv, prop/stands.csv, T-Motor test rows).
Then scans the repo's text files for URLs and exits non-zero if a URL is not
indexed (non-data links such as font licences and XML schemas are exempt).
"""
import csv
import datetime as dt
import re
import sys
import tomllib
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUTFILE = REPO / "SOURCES.md"
URL_RX = re.compile(r"https?://[^\s\"'<>`)\]}|]+")
SCAN_EXT = {".py", ".toml", ".tex", ".md", ".csv", ".txt", ".sh"}
SKIP_DIRS = {".git", "raw", "out", "build", "__pycache__", "claude_docs", "fonts"}
SKIP_FILES = {"SOURCES.md", "sources.lock"}
NOT_DATA = ("schemas.openxmlformats.org", "purl.org/dc", "www.w3.org", "openfontlicense.org", "scripts.sil.org",
            "github.com/vercel/geist-font")


def toml(path):
    with path.open("rb") as f:
        return tomllib.load(f)


def lock(path):
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        parts = [p.strip() for p in line.split(",")]
        out[parts[0]] = parts[1:]
    return out


def norm_url(u):
    return re.sub(r"[.,;:*]+$", "", u).split("?")[0].rstrip("/").replace("http://", "https://")


def usage():
    c = Counter()
    for name, col in (("dbf_aircraft.csv", "source"), ("dbf_results.csv", "source_id"),
                      ("prop/components.csv", "source"), ("prop/stands.csv", "source")):
        f = HERE / name
        if f.exists():
            for r in csv.DictReader(f.open(encoding="utf-8")):
                c[r[col]] += 1
    try:
        sys.path.insert(0, str(HERE / "prop"))
        import propdata
        for sid in [s["id"] for s in toml(HERE / "prop" / "sources.toml")["source"] if s["id"].startswith("tmotor-")]:
            c[sid] += sum(len(v) for v in propdata.tmotor_tests(sid).values())
        c["apc-perfiles-202602"] = len(propdata.apc_names())
        c["uiuc-propdb-zip"] = sum(len(propdata.uiuc_runs(n)["runs"]) + 1 for n in propdata.UIUC_VOL4) + \
            sum(len(propdata.uiuc_runs(n, "volume-1")["runs"]) + 1 for n in propdata.UIUC_VOL1_LARGE)
    except Exception as e:                       # raw cache missing: counts from CSVs only
        print(f"note: propulsion counts skipped ({e})")
    return c


def used_label(sid, c):
    n = c.get(sid, 0)
    if sid == "apc-perfiles-202602":
        return f"{n} computed propeller tables"
    if sid == "uiuc-propdb-zip":
        return f"{n} measured runs of the 20 APC-E props compared"
    if sid.startswith("tmotor-"):
        return f"{n} measured test rows + spec table" if n else "spec table only (no test table)"
    if sid == "apc-price-list-202602":
        return "list prices for the PR-01 proposals"
    if sid.startswith("aiaa-dbf-") and sid.endswith("-rules"):
        return "rule comparisons with past years (quoted in notes)"
    if n:
        return f"{n} verified value{'s' if n > 1 else ''}"
    return "read for context; no dataset values"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    c = usage()
    aiaa, aiaa_lock = toml(HERE / "sources.toml")["source"], lock(HERE / "sources.lock")
    prop, prop_lock = toml(HERE / "prop" / "sources.toml")["source"], lock(HERE / "prop" / "sources.lock")
    other = toml(HERE / "other_sources.toml")["source"]
    pr = [r for r in csv.DictReader((REPO / "procurement" / "pr01_items.csv").open(encoding="utf-8-sig")) if r["ref_url"].strip()]
    brain = sorted({norm_url(u) for u in URL_RX.findall((REPO / "brainstorm.md").read_text(encoding="utf-8"))})

    L = ["# Sources", "",
         f"Every source behind a number in this repository, with its link. Generated by "
         f"`python analysis/data/sources_index.py` on {dt.date.today().isoformat()}; do not edit by hand.", "",
         "- **Primary sources only** for values: the publisher of a document is the authority for it. Retail-only data "
         "is marked RESELLER and never decides anything.",
         "- **Nature:** MEASURED (a test or observation), SPEC (a manufacturer's rating or statement), COMPUTED (a "
         "model's output, e.g. APC's propeller tables), RULE, METHOD (an equation or tool), CONSULTED (read, no value used).",
         "- **Re-checkable:** files the analysis read are hashed (SHA-256, first 12 characters shown; full hashes in "
         "`analysis/data/sources.lock` and `analysis/data/prop/sources.lock`). Every quoted value is checked against "
         "the cached file by `analysis/data/verify.py` and `analysis/data/prop/verify_prop.py`.",
         "- **Values used:** how many verified values each source supplies to the analysis datasets.", ""]

    L += ["## 1. Rules, site and weather", "", "| Source | Publisher | Nature | Used for | Link |", "|---|---|---|---|---|"]
    for s in other:
        if s["id"] in ("rules-2027-draft", "iem-asos", "usgs-epqs", "timpa-location", "ncei-normals-ktus"):
            L.append(f"| {s['title']} | {s['publisher']} | {s['nature']} | {s['used_for']} | {s['url']} |")

    L += ["", "## 2. AIAA Design/Build/Fly documents", "",
          "Competition summaries (every team's scores), top-3 design reports and proposals, and past rules. Index page: "
          "https://aiaa.org/get-involved/university-students/dbf/previous-competitions/", "",
          "| Document | Pages | SHA-256 | Fetched | Values used | Link |", "|---|---|---|---|---|---|"]
    for s in aiaa:
        lk = aiaa_lock.get(s["id"], ["", "", "", ""])
        url = s["url"] if not s["url"].startswith("repo:") else f"repo file `{s['url'][5:]}`"
        L.append(f"| {s['title']} | {lk[2]} | `{lk[0][:12]}` | {lk[3]} | {used_label(s['id'], c)} | {url} |")

    L += ["", "## 3. Propulsion (Script 3b)", "", "| Source | Publisher | Nature | SHA-256 | Fetched | Values used | Link |",
          "|---|---|---|---|---|---|---|"]
    for s in prop:
        lk = prop_lock.get(s["id"], ["", "", "", ""])
        L.append(f"| {s['title']} | {s['publisher']} | {s['nature']} | `{lk[0][:12]}` | {lk[2]} | "
                 f"{used_label(s['id'], c)} | {s['url']} |")

    refs = sorted({s_["referer"] for s_ in prop if s_.get("referer")})
    L += ["", "APC files are downloaded from APC's downloads page (opened first as the Referer): " + ", ".join(refs)]
    groups = (("## 4. Deploy-and-recover mechanism parts (Table 06 trade)",
               lambda s: s["id"].startswith(("pololu", "gobilda", "rev-", "adafruit", "goodfellow", "reseller"))),
              ("## 5. Methods and tools", lambda s: s["nature"] == "METHOD"),
              ("## 6. Consulted, no value used", lambda s: s["nature"] == "CONSULTED"),
              ("## 7. R&D notes references (context only, no analysis value; quality in Status)",
               lambda s: s["nature"] == "NOTE"))
    for head, sel in groups:
        L += ["", head, "", "| Source | Publisher | Status | Used for | Link |", "|---|---|---|---|---|"]
        for s in other:
            if sel(s):
                L.append(f"| {s['title']} | {s['publisher']} | {s['status']} | {s['used_for']} | {s['url'] or 'no URL (book or retail search)'} |")

    L += ["", "## 8. Procurement price links (PR-01)", "",
          "Reference prices for the purchase request (`procurement/pr01_items.csv`); each was read on the stated date. "
          "Retail prices move: confirm at order.", "", "| PR-01 | Item | Vendor | Checked | Link |", "|---|---|---|---|---|"]
    for r in pr:
        L.append(f"| {r['id']} | {r['item']} | {r['ref_vendor']} | {r['checked']} ({r['checked_via']}) | {r['ref_url']} |")

    L += ["", "## 9. Brainstorm notes (feasibility only, no analysis value)", "",
          "Links behind `brainstorm.md` (ground radar / camera tracking idea).", ""]
    L += [f"- {u}" for u in brain]

    # completeness: every URL in the repo's text files must be indexed (or be a non-data link)
    indexed = {norm_url(u) for u in URL_RX.findall("\n".join(L))}
    for s in other:
        indexed |= {norm_url(u) for u in s.get("also", [])}
    missing = []
    for f in REPO.rglob("*"):
        if (not f.is_file() or f.suffix not in SCAN_EXT or f.name in SKIP_FILES
                or any(p in SKIP_DIRS for p in f.relative_to(REPO).parts)):
            continue
        for u in URL_RX.findall(f.read_text(encoding="utf-8", errors="replace")):
            n = norm_url(u)
            if any(x in n for x in NOT_DATA) or "{" in n:
                continue
            if not any(n == i or i.startswith(n) or n.startswith(i) for i in indexed):
                missing.append(f"{f.relative_to(REPO)}: {u}")
    L += ["", "## Completeness check", ""]
    L.append("Every link found in the repository's code, inputs, data and documents is listed above."
             if not missing else "**Links found in the repository but missing from this index:**")
    L += [f"- {m}" for m in missing]
    OUTFILE.write_text("\n".join(L) + "\n", encoding="utf-8")
    n_src = len(aiaa) + len(prop) + len(other)
    print(f"wrote {OUTFILE.name}: {n_src} sources ({len(aiaa)} AIAA, {len(prop)} propulsion, {len(other)} other), "
          f"{len(pr)} price links, {len(brain)} brainstorm links; {len(missing)} unindexed links")
    for m in missing:
        print("  MISSING", m)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
