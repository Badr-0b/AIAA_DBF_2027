"""Script 3b predictions printed on test card TC-06 (propulsion bench), so every bench
reading is checked against the model on the spot (TOOLING).

    python analysis/tc06_predictions.py

For each bench configuration (both D9 candidate systems, the propeller sweep of
PR-01 B09/B09b) it gives, static (v = 0), at rho = 1.17 kg/m3:
- at fixed RPM steps: thrust and torque (APC tables: the propeller check) and the
  battery current and power at a fresh pack (T-Motor map + pack model: the motor
  and battery check);
- the full-throttle point: the largest static thrust meeting every limit (APC RPM
  limit, voltage, current cap) and which limit binds.
Thrust and torque scale with air density at fixed RPM; the card tells the crew to
rescale with the measured density. Writes out/tc06_predictions.csv and
testing/cards/tc06_predictions.tex (the card's prediction table).
"""
import csv
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
import s3b_propulsion as pb  # noqa: E402

RHO = 1.17          # kg/m3: sea level at about 28 C, the bench in Kuwait in Oct-Nov (card rescales)
V_OC = 4.15         # V/cell: fresh pack, as propulsion.toml v_oc_start
RPMS = [3000, 4000, 5000, 6000, 7000]
CONFIGS = [
    ("8S", "tp3300-8se55", ("tmotor-at7215", "KV270"), ["20x15E", "20x13E", "205x14E", "21x13E"]),
    ("12S", "maxamps-12s-2000", ("tmotor-at7215", "KV200"), ["20x15E", "20x13E", "205x14E", "21x13E"]),
]
OUT = HERE / "out" / "tc06_predictions.csv"
TEX = HERE.parent / "testing" / "cards" / "tc06_predictions.tex"


def binding(sysm, t):
    p = sysm.point(RHO, t * 1.002, 0.0, V_OC)
    rpm, i = float(p["rpm"]), float(p["i"])
    w = rpm * pb.RPM_TO_RAD
    q = float(p["q"])
    if rpm > sysm.prop.rpm_limit:
        return "APC RPM limit"
    if not i <= sysm.i_cap:
        return f"current cap {sysm.i_cap:.0f} A"
    if sysm.motor.volts_needed(w, q, i) > float(p["volts"]):
        return "pack voltage"
    return "?"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    rows = []
    for cells, pack, motor, props in CONFIGS:
        for pn in props:
            sysm = pb.System(pb.Prop(pn), pb.MapMotor(*motor), pb.Battery.from_components(pack))
            tmax = float(sysm.thrust_max(RHO, np.array(0.0), V_OC))
            p = sysm.point(RHO, tmax, 0.0, V_OC)
            for rpm in RPMS:
                if rpm >= float(p["rpm"]):          # not reachable on this pack and fuse
                    continue
                t, p_sh = (float(x) for x in sysm.prop.thrust_power(RHO, np.array(rpm, float), np.array(0.0)))
                w = rpm * pb.RPM_TO_RAD
                q = p_sh / w
                p_in = float(sysm.motor.p_in(w, q))
                i = float(sysm.battery.current(p_in, V_OC))
                rows.append({"cells": cells, "motor": f"AT7215 {motor[1]}", "prop": pn, "kind": "rpm step",
                             "rpm": rpm, "thrust_n": t, "torque_nm": q, "current_a": i, "p_batt_w": p_in,
                             "limit": ""})
            rows.append({"cells": cells, "motor": f"AT7215 {motor[1]}", "prop": pn, "kind": "full throttle",
                         "rpm": float(p["rpm"]), "thrust_n": tmax, "torque_nm": float(p["q"]),
                         "current_a": float(p["i"]), "p_batt_w": float(p["p_batt"]), "limit": binding(sysm, tmax)})
    OUT.parent.mkdir(exist_ok=True)
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    write_tex(rows)
    for r in rows:
        print(f"{r['cells']:>3} {r['motor']:<13} {r['prop']:<8} {r['kind']:<13} {r['rpm']:>6.0f} rpm "
              f"{r['thrust_n']:>6.1f} N {r['torque_nm']:>5.2f} N.m {r['current_a']:>6.1f} A {r['p_batt_w']:>6.0f} W  {r['limit']}")


def write_tex(rows):
    def prop_label(p):
        return p.replace("205x", "20.5x").replace("x", r"$\times$")
    L = ["% GENERATED by analysis/tc06_predictions.py: do not edit. Script 3b, static, rho 1.17 kg/m3, 4.15 V/cell.",
         r"\begin{dbftable}{colspec={Q[c,wd=0.45in] Q[c,wd=0.85in] Q[c,wd=0.5in] Q[c,wd=0.6in] Q[c,wd=0.7in] "
         r"Q[c,wd=0.8in] Q[c,wd=0.75in] Q[c,wd=0.7in] X[l]}, row{2-Z}={valign=m}, "
         r"cells={font=\dbftablefont\footnotesize}, rowsep=1.2pt}",
         r"Pack & Prop & Point & RPM & Thrust, N & Torque, N·m & Current, A & Power, W & Limit \\"]
    for r in rows:
        point = "full" if r["kind"] == "full throttle" else "step"
        L.append(f"{r['cells']} & {prop_label(r['prop'])} & {point} & {r['rpm']:.0f} & "
                 f"{r['thrust_n']:.1f} & {r['torque_nm']:.2f} & {r['current_a']:.1f} & {r['p_batt_w']:.0f} & {r['limit']} \\\\")
    L.append(r"\end{dbftable}")
    TEX.write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
