"""Script 7: export the analysis into the proposal (TOOLING; R&D Sec. 4).

    python analysis/s7_export.py        (proposal/build.sh runs it)

Writes proposal/data/analysis.tex: the Table 08 and glance-panel numbers and
the SR-18 load factor, computed by Scripts 1-2 for the aircraft and the
competitor scenario named in inputs/export.toml.

Contract:
- Every macro lives in exactly one file. A macro written here must not also be
  defined in proposal/data/numbers.tex: this script refuses, and LaTeX would
  stop on the duplicate \\newcommand anyway.
- Until export.toml says confirmed = true (numbers freeze, 20 Oct), each value
  prints as an unfinished value, \\dbftbd{6.39}: visible in the draft, counted
  by build.sh.
- A value that cannot be computed yet (target nan, function not written)
  prints as \\dbftbd{<label>}, the same placeholder numbers.tex used before.
"""
import re
import sys

import common
import run_all
import s1_course as s1
import s2_scoring as s2
from run_all import Missing, attempt, need

TARGET = common.PROPOSAL / "data" / "analysis.tex"
NUMBERS = common.PROPOSAL / "data" / "numbers.tex"


class Results:
    """Scripts 1-2 for one aircraft, computed once, on demand."""

    def __init__(self, key, scenario):
        self.p = common.aircraft(key)
        self.scenario = scenario
        self._perf = self._scores = None

    def perf(self):
        if self._perf is None:
            self._perf = run_all.performance(self.p)
        return self._perf

    def scores(self, scenario=None):
        return run_all.scores(self.p, self.perf(), scenario or self.scenario)

    def get(self, *keys):
        values = need(self.p, *keys)
        return values[0] if len(values) == 1 else values


# macro, placeholder label (as numbers.tex had it), value
SPEC = [
    ("nMtwoUnits", "units", lambda r: f"{int(r.get('n_sim')) + 1:d}"),
    ("nMtwoPayload", "m payload", lambda r: f"{attempt(s2.m2_payload_mass, *r.get('n_sim', 'm_container_kg', 'm_sensor_max_kg')):.2f}"),
    ("nMtwoTime", "5-lap time", lambda r: f"{r.perf()['t_m2']:.1f}"),
    ("nLapTime", "lap time", lambda r: f"{r.perf()['t_lap']:.1f}"),
    ("nLoadFactor", "n turn", lambda r: f"{r.perf()['n']:.2f}"),
    ("nMthreeLaps", "laps", lambda r: f"{r.perf()['m3_laps']:.0f}"),
    ("nMthreeSensor", "m sensor M3", lambda r: f"{r.get('m_sensor_m3_kg'):.2f}"),
    ("nSensorWeight", "m sensor", lambda r: f"{r.get('m_sensor_max_kg'):.2f}"),
    ("nDropHeight", "h", lambda r: f"{attempt(s2.declared_drop_height, r.get('h_drop_m')):.4f}".rstrip("0").rstrip(".")),
    ("nDropHeightIn", "h in", lambda r: f"{attempt(s2.declared_drop_inches, r.get('h_drop_m')):.0f}"),
    ("sMone", "M1", lambda r: f"{r.scores()['M1']:.2f}"),
    ("sMtwo", "M2", lambda r: f"{r.scores()['M2']:.2f}"),
    ("sMthree", "M3", lambda r: f"{r.scores()['M3']:.2f}"),
    ("sGM", "GM", lambda r: f"{r.scores()['GM']:.2f}"),
    ("sTotal", "total", lambda r: f"{r.scores()['total']:.2f}"),
    ("sTotalAggressive", "total agg.", lambda r: f"{r.scores('aggressive')['total']:.2f}"),
    ("sTotalConservative", "total cons.", lambda r: f"{r.scores('conservative')['total']:.2f}"),
]


def defined_in_numbers():
    text = NUMBERS.read_text(encoding="utf-8")
    return set(re.findall(r"^\s*\\newcommand\\([A-Za-z]+)", text, flags=re.M))


def main():
    cfg = common.load("export")
    clash = sorted(defined_in_numbers() & {name for name, _, _ in SPEC})
    if clash:
        sys.exit("s7_export: " + ", ".join("\\" + c for c in clash) + " still defined in "
                 "proposal/data/numbers.tex; each macro lives in one file (replace the "
                 "numbers.tex line with a pointer comment)")
    results = Results(cfg["selected"], cfg["scenario"])
    lines = ["% GENERATED by analysis/s7_export.py from analysis/inputs/ (Scripts 1-2).",
             "% Do not edit: change the inputs or the scripts and rebuild.",
             f"% Aircraft {cfg['selected']}, competitor scenario '{cfg['scenario']}', "
             f"confirmed = {str(cfg['confirmed']).lower()}."]
    done, waiting = 0, []
    for name, label, value in SPEC:
        try:
            text = value(results)
            done += 1
            body = text if cfg["confirmed"] else rf"\dbftbd{{{text}}}"
        except (Missing, NotImplementedError, KeyError) as e:
            waiting.append(name)
            body = rf"\dbftbd{{{label}}}"
            lines.append(f"% \\{name}: {e}")
        lines.append(rf"\newcommand\{name}{{{body}}}")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    state = "confirmed" if cfg["confirmed"] else "NOT confirmed: values print as unfinished"
    print(f"ok    data/analysis.tex  | {done} of {len(SPEC)} values computed "
          f"(aircraft {cfg['selected']}, scenario {cfg['scenario']}; {state})")


if __name__ == "__main__":
    main()
